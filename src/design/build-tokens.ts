// Builds assets/design/tokens.css from MSP's brand colours: OKLCH ramps gamut-mapped to sRGB, frozen as
// hex, plus a WCAG contrast gate for every text pairing the templates are allowed to use.
//
//   node src/design/build-tokens.ts
import { writeFileSync, mkdirSync } from 'node:fs';
import { converter, formatHex, toGamut, wcagContrast } from 'culori';

// Brand colours from the MSP design system (docs/design-system/README.md in the app repo).
export const brand = {
  coral: '#ec726f',      // marketing and social coral
  coralSite: '#fe696a',  // the site's CSS primary
  indigo: '#4e54c8',
  sky: '#69b3fe',
  green: '#42d697',
  orange: '#fea569',
  navy: '#2b3445',       // gray-900, the house ink
  gray800: '#373f50',
  gray700: '#4b566b',
  gray600: '#7d879c',
  gray300: '#e3e9ef',
  gray200: '#f3f5f9',
  gray100: '#f6f9fc',
  white: '#ffffff',
};

const oklch = converter('oklch');
const toSrgb = toGamut('rgb', 'oklch');

// Ramp stops relative to the brand colour's own lightness (500 is the brand colour itself):
// tints move towards white, shades towards black, so every ramp is monotonic whatever its base.
const tints: Record<string, number> = { 50: 0.93, 100: 0.84, 200: 0.68, 300: 0.48, 400: 0.24 };
const shades: Record<string, number> = { 600: 0.86, 700: 0.73, 800: 0.6, 900: 0.47 };

function ramp(hex: string): Record<string, string> {
  const base = oklch(hex)!;
  const out: Record<string, string> = { 500: hex };
  const stops = {
    ...Object.fromEntries(Object.entries(tints).map(([k, f]) => [k, base.l + (1 - base.l) * f])),
    ...Object.fromEntries(Object.entries(shades).map(([k, f]) => [k, base.l * f])),
  };
  for (const [name, l] of Object.entries(stops)) {
    // Chroma tapers towards white and black so tints stay clean and shades don't go muddy.
    const taper = l > base.l ? 1 - ((l - base.l) / (1 - base.l)) ** 1.6 : 1 - ((base.l - l) / base.l) ** 2.2 * 0.35;
    out[name] = formatHex(toSrgb({ mode: 'oklch', l, c: (base.c ?? 0) * Math.max(0.08, taper), h: base.h }));
  }
  return Object.fromEntries(Object.entries(out).sort((a, b) => Number(a[0]) - Number(b[0])));
}

const ramps = { coral: ramp(brand.coral), indigo: ramp(brand.indigo), sky: ramp(brand.sky) };

// Semantic tokens: what templates use. Raw ramps stay available for charts.
const semantic = {
  ink: brand.navy,
  'ink-soft': brand.gray700,
  'ink-muted': '#626c80',       // darker than the site's gray-600 so 30px source lines pass AA
  paper: brand.white,
  'paper-warm': '#fbf7f3',
  'paper-cool': brand.gray100,
  line: brand.gray300,
  context: '#dfe3ea',        // light grey for context marks, distinct in lightness from coral
  highlight: brand.coral,    // fill/highlight only, never small text on white
  'highlight-text': brand.indigo,
  accent: brand.indigo,
  sky: brand.sky,
};

// Allowed text pairings: [foreground, background, minimum ratio, note].
const pairs: Array<[string, string, number, string]> = [
  [semantic.ink, semantic.paper, 4.5, 'body/headlines on white'],
  [semantic['ink-soft'], semantic.paper, 4.5, 'secondary text on white'],
  [semantic['ink-muted'], semantic.paper, 4.5, 'source lines'],
  [semantic['ink-muted'], semantic['paper-warm'], 4.5, 'source lines on warm paper'],
  [semantic.ink, semantic['paper-warm'], 4.5, 'text on warm paper'],
  [semantic.accent, semantic.paper, 4.5, 'indigo highlight text'],
  [semantic.paper, semantic.ink, 4.5, 'white on navy'],
  [semantic.paper, semantic.accent, 4.5, 'white on indigo'],
  [brand.coral, semantic.ink, 3, 'coral on navy: large text only (≥51px bold)'],
  [semantic.ink, brand.coral, 3, 'navy on coral: large text only'],
  [semantic.ink, ramps.coral['100'], 4.5, 'navy on coral tint'],
  [semantic.ink, ramps.sky['100'], 4.5, 'navy on sky tint'],
];

const failures: string[] = [];
const report = pairs.map(([fg, bg, min, note]) => {
  const ratio = wcagContrast(fg, bg);
  if (ratio < min) failures.push(`${note}: ${ratio.toFixed(2)} < ${min}`);
  return `/* ${ratio.toFixed(2)}:1 (min ${min}) ${note} */`;
});

const css = [
  '/* Generated by src/design/build-tokens.ts. Do not edit by hand. */',
  ':root {',
  ...Object.entries(semantic).map(([k, v]) => `  --${k}: ${v};`),
  ...Object.entries(ramps).flatMap(([name, r]) => Object.entries(r).map(([k, v]) => `  --${name}-${k}: ${v};`)),
  ...Object.entries(brand).map(([k, v]) => `  --brand-${k.replace(/[A-Z]/g, m => '-' + m.toLowerCase())}: ${v};`),
  '}',
  '',
  '/* Contrast gate */',
  ...report,
  '',
].join('\n');

mkdirSync('assets/design', { recursive: true });
writeFileSync('assets/design/tokens.css', css);
writeFileSync('assets/design/tokens.json', JSON.stringify({ semantic, ramps, brand }, null, 2) + '\n');
console.log(report.join('\n'));
if (failures.length) {
  console.error('\nContrast gate FAILED:\n  ' + failures.join('\n  '));
  process.exit(1);
}
console.log('\ntokens written: assets/design/tokens.css, assets/design/tokens.json');
